"use client";

import { useEffect, useState } from "react";
import { getReport, getReportPDF, getUpcomingMatches } from "@/lib/api";
import { Card, EmptyState, ErrorNote, SectionHeader } from "@/components/ui";
import { DataSourceBadge } from "@/components/DataSourceBadge";
import { formatDateTime } from "@/lib/utils";
import type { MatchResearchSnapshot } from "@/types";

export default function ReportsPage() {
  const [reports, setReports] = useState<MatchResearchSnapshot[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [downloading, setDownloading] = useState<string | null>(null);

  useEffect(() => {
    async function loadReports() {
      setLoading(true);
      try {
        const fixtures = await getUpcomingMatches(10);
        if (fixtures.matches.length === 0) {
          setReports([]);
          setError("No upcoming fixtures available to generate reports.");
          return;
        }

        const reportResults = await Promise.allSettled(
          fixtures.matches.slice(0, 8).map((match) => getReport(match.match_id))
        );

        const liveReports = reportResults
          .filter(
            (result): result is PromiseFulfilledResult<MatchResearchSnapshot> =>
              result.status === "fulfilled"
          )
          .map((result) => result.value);

        setReports(liveReports);
        setError(
          liveReports.length === 0 ? "The backend could not generate any report." : null
        );
      } catch {
        setError("Could not load reports.");
      } finally {
        setLoading(false);
      }
    }

    loadReports();
  }, []);

  const handleDownloadPDF = async (matchId: string) => {
    setDownloading(matchId);
    try {
      const blob = await getReportPDF(matchId);
      const url = window.URL.createObjectURL(blob);
      const anchor = document.createElement("a");
      anchor.href = url;
      anchor.download = `match-report-${matchId}.pdf`;
      document.body.appendChild(anchor);
      anchor.click();
      window.URL.revokeObjectURL(url);
      document.body.removeChild(anchor);
    } catch {
      setError("The PDF could not be downloaded.");
    } finally {
      setDownloading(null);
    }
  };

  return (
    <div className="animate-rise">
      <SectionHeader
        title="Reports"
        description="Match research snapshots for the next fixtures, generated by the backend from the same model the board uses."
        actions={
          <DataSourceBadge label="Live API" detail="report snapshots and PDFs" tone="live" />
        }
      />

      {error ? <ErrorNote>{error}</ErrorNote> : null}

      {loading ? (
        <Card className="px-6 py-14 text-center text-[13px] text-ink-soft">
          Generating reports…
        </Card>
      ) : reports.length === 0 ? (
        <EmptyState
          title="No reports yet"
          description="No report could be generated from the fixtures currently in the database."
        />
      ) : (
        <ul className="space-y-3">
          {reports.map((report) => (
            <li key={report.match_id}>
              <Card className="flex flex-wrap items-center justify-between gap-4 px-5 py-4">
                <div className="min-w-0">
                  <p className="text-[15px] font-medium text-ink">
                    {report.home_team}
                    <span className="px-1.5 text-ink-mute">vs</span>
                    {report.away_team}
                  </p>
                  <p className="mt-1 font-mono text-[11px] text-ink-mute">
                    {report.league.replaceAll("_", " ")} ·{" "}
                    {formatDateTime(report.generated_at)}
                  </p>
                </div>

                <div className="flex items-center gap-6">
                  <p className="tnum font-mono text-[12px] text-ink-soft">
                    {(report.home_win_prob * 100).toFixed(0)}/
                    {(report.draw_prob * 100).toFixed(0)}/
                    {(report.away_win_prob * 100).toFixed(0)}
                  </p>
                  <button
                    onClick={() => handleDownloadPDF(report.match_id)}
                    disabled={downloading === report.match_id}
                    className="rounded-lg border border-white/10 px-3 py-1.5 text-[12px] text-ink-soft transition-colors duration-150 ease-out hover:border-white/20 hover:text-ink disabled:opacity-50"
                  >
                    {downloading === report.match_id ? "Downloading…" : "PDF"}
                  </button>
                </div>
              </Card>
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}
